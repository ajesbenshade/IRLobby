def parse_origin_list(value):
    return [item.strip() for item in value.split(",") if item.strip()]


def validate_origin_list(setting_name, origins, *, require_https):
    invalid_origins = []
    placeholder_origins = []

    for origin in origins:
        parsed = urlparse(origin)
        if parsed.scheme not in {"http", "https"} or not parsed.netloc:
            invalid_origins.append(origin)
            continue
        if require_https and parsed.scheme != "https":
            invalid_origins.append(origin)
        if any(
            placeholder in origin for placeholder in ["your-domain.com", "your-frontend-domain.com"]
        ):
            placeholder_origins.append(origin)

    if invalid_origins:
        raise ImproperlyConfigured(
            f"{setting_name} contains invalid production origins: {', '.join(invalid_origins)}"
        )
    if placeholder_origins:
        raise ImproperlyConfigured(
            f"{setting_name} contains placeholder production origins: {', '.join(placeholder_origins)}"
        )


def validate_redis_url(setting_name, redis_url, *, require_auth):
    parsed = urlparse(redis_url)
    if parsed.scheme not in {"redis", "rediss"} or not parsed.hostname:
        raise ImproperlyConfigured(f"{setting_name} must be a valid redis:// or rediss:// URL.")
    if require_auth and not parsed.password:
        raise ImproperlyConfigured(
            f"{setting_name} must include Redis authentication in production."
        )


